<?php

namespace App\Http\Controllers;

use Illuminate\Http\Request;
use App\Models\Notification;
use Illuminate\Support\Facades\Auth;

class NotificationController extends Controller
{
    public function index()
    {
        $userId = Auth::id() ?? 1;
        $notifications = Notification::where('user_id', $userId)
            ->orderBy('created_at', 'desc')
            ->get();

        // Seed initial notifications if user has none so notifications and alerts are active
        if ($notifications->isEmpty()) {
            $defaultNotifications = [
                [
                    'user_id'    => $userId,
                    'title'      => 'Learning Roadmap Milestone Ready',
                    'message'    => 'Phase 1: Backend Architecture fundamentals is ready to begin. 5 modules available.',
                    'status'     => 'unread',
                    'created_at' => now()->subMinutes(25),
                    'updated_at' => now()->subMinutes(25),
                ],
                [
                    'user_id'    => $userId,
                    'title'      => 'AI Skill Gap Analysis Completed',
                    'message'    => 'Identified missing skills in System Design and Docker for your target career.',
                    'status'     => 'unread',
                    'created_at' => now()->subHours(3),
                    'updated_at' => now()->subHours(3),
                ],
                [
                    'user_id'    => $userId,
                    'title'      => 'Mock Interview Session Available',
                    'message'    => 'Test your knowledge with 3 tailored technical questions generated by Aria AI.',
                    'status'     => 'read',
                    'created_at' => now()->subHours(18),
                    'updated_at' => now()->subHours(18),
                ],
                [
                    'user_id'    => $userId,
                    'title'      => 'Career Recommendation Generated',
                    'message'    => 'Your profile matches 94% with Full Stack Software Engineer roles.',
                    'status'     => 'read',
                    'created_at' => now()->subDays(2),
                    'updated_at' => now()->subDays(2),
                ],
                [
                    'user_id'    => $userId,
                    'title'      => 'Welcome to Aria Assistant',
                    'message'    => 'Complete your skills profile to unlock fully personalized AI roadmaps.',
                    'status'     => 'read',
                    'created_at' => now()->subDays(4),
                    'updated_at' => now()->subDays(4),
                ]
            ];

            foreach ($defaultNotifications as $item) {
                Notification::create($item);
            }

            $notifications = Notification::where('user_id', $userId)
                ->orderBy('created_at', 'desc')
                ->get();
        }

        return response()->json([
            'success'      => true,
            'data'         => $notifications,
            'unread_count' => $notifications->where('status', 'unread')->count(),
        ]);
    }

    public function markAsRead($id)
    {
        $userId = Auth::id() ?? 1;
        $notification = Notification::where('user_id', $userId)->where('id', $id)->first();

        if ($notification) {
            $notification->status = 'read';
            $notification->save();
        }

        return response()->json([
            'success' => true,
            'message' => 'Notification marked as read.',
            'data'    => $notification
        ]);
    }

    public function markAllAsRead()
    {
        $userId = Auth::id() ?? 1;
        Notification::where('user_id', $userId)
            ->where('status', 'unread')
            ->update(['status' => 'read']);

        return response()->json([
            'success' => true,
            'message' => 'All notifications marked as read.'
        ]);
    }

    public function destroy($id)
    {
        $userId = Auth::id() ?? 1;
        Notification::where('user_id', $userId)->where('id', $id)->delete();

        return response()->json([
            'success' => true,
            'message' => 'Notification deleted.'
        ]);
    }
}
